function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}

function stars(level) {
  return "★".repeat(level) + "☆".repeat(Math.max(0, 3 - level));
}

function paragraphize(lines) {
  return lines
    .map((line, index) => {
      const cls = index === 2 && lines.length >= 5 ? ' class="intent-key"' : "";
      return `<p${cls}>${escapeHtml(line)}</p>`;
    })
    .join("");
}

function renderSigns(items, type) {
  const warningClass = type === "warning" ? " sign-item--warning" : "";

  return items
    .map(([title, body], index) => `
      <article class="sign-item${warningClass}">
        <p class="sign-item__title">${String(index + 1).padStart(2, "0")}｜${escapeHtml(title)}</p>
        <p>${escapeHtml(body)}</p>
      </article>
    `)
    .join("");
}


