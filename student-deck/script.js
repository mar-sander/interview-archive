const AUTH_KEY = "employment_final_training_auth_v1";
const AUTH_HASH = "2f437e589a83bb85585630820b729a74ba1c1d068f87f7d614ec1cdcb651fc56";

async function sha256(value) {
  if (!window.crypto?.subtle) {
    throw new Error("このブラウザーでは認証機能を利用できません。");
  }

  const bytes = new TextEncoder().encode(value);
  const digest = await crypto.subtle.digest("SHA-256", bytes);

  return [...new Uint8Array(digest)]
    .map((byte) => byte.toString(16).padStart(2, "0"))
    .join("");
}

function setAuthError(message = "") {
  const error = document.getElementById("authError");
  if (error) error.textContent = message;
}

function unlockSite() {
  document.body.classList.remove("auth-locked");
  document.body.classList.add("auth-unlocked");
  document.getElementById("authGate")?.setAttribute("aria-hidden", "true");
  setAuthError("");
}

function lockSite({ focus = true } = {}) {
  document.body.classList.remove("auth-unlocked");
  document.body.classList.add("auth-locked");
  document.getElementById("authGate")?.removeAttribute("aria-hidden");

  const input = document.getElementById("authPassword");
  if (input) input.value = "";

  setAuthError("");

  if (focus) {
    setTimeout(() => input?.focus(), 30);
  }
}

function hasSavedAuth() {
  try {
    return localStorage.getItem(AUTH_KEY) === AUTH_HASH;
  } catch (error) {
    return false;
  }
}

function saveAuth() {
  try {
    localStorage.setItem(AUTH_KEY, AUTH_HASH);
    return true;
  } catch (error) {
    return false;
  }
}

function bindAuth() {
  const form = document.getElementById("authForm");
  const input = document.getElementById("authPassword");

  if (hasSavedAuth()) {
    unlockSite();
  } else {
    lockSite({ focus: true });
  }

  form?.addEventListener("submit", async (event) => {
    event.preventDefault();

    const value = input?.value ?? "";

    if (!value) {
      setAuthError("パスワードを入力してください。");
      input?.focus();
      return;
    }

    const submit = form.querySelector('[type="submit"]');
    submit.disabled = true;
    submit.textContent = "確認しています…";
    setAuthError("");

    try {
      const hash = await sha256(value);

      if (hash !== AUTH_HASH) {
        setAuthError("パスワードが違います。入力内容を確認してください。");
        input?.select();
        return;
      }

      saveAuth();
      unlockSite();
    } catch (error) {
      setAuthError(error?.message || "認証中にエラーが発生しました。");
    } finally {
      submit.disabled = false;
      submit.textContent = "DECKを開く";
    }
  });
}


